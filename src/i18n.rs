use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
pub enum Language {
    #[serde(rename = "ru")]
    #[default]
    Ru,
    #[serde(rename = "en")]
    En,
    #[serde(rename = "hr")]
    Hr,
}

impl Language {
    pub fn display_name(self) -> &'static str {
        match self {
            Language::Ru => "Русский",
            Language::En => "English",
            Language::Hr => "Hrvatski",
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, Default)]
pub enum ThemeMode {
    #[serde(rename = "system")]
    #[default]
    System,
    #[serde(rename = "dark")]
    Dark,
    #[serde(rename = "light")]
    Light,
}

impl ThemeMode {
    pub fn resolve_is_dark(self) -> bool {
        match self {
            ThemeMode::System => crate::platform::is_system_dark_theme(),
            ThemeMode::Dark => true,
            ThemeMode::Light => false,
        }
    }
}

